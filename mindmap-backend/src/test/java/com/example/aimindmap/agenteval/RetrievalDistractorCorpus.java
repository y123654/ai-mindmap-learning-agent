    private static DistractorChunk chunk(long sourceId, String group, String title, String content) {
        String documentName = "操作系统笔记-" + shortTitle(title) + ".md";
        return new DistractorChunk(sourceId, group, title, content,
                List.of(documentName, title));
    }

    /** 文件名里不用长标题：取冒号/顿号前的主干，避免路径里出现奇怪符号。 */
    private static String shortTitle(String title) {
        String stem = title;
        for (String separator : List.of("：", ":", "（", "(", " ")) {
            int index = stem.indexOf(separator);
            if (index > 0) {
                stem = stem.substring(0, index);
            }
        }
        return stem;
    }

    /** 全部干扰的 source_id（字符串形式，用于精确删除与命中判定）。 */
    static List<String> sourceIds() {
        return all().stream().map(item -> String.valueOf(item.sourceId())).toList();
    }
